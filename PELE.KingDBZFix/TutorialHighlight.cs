        private static readonly Dictionary<string, Regex> Patterns = new Dictionary<string, Regex>(StringComparer.OrdinalIgnoreCase);
        private static readonly object PatternLock = new object();

        internal static string Apply(string language, string token, string text)
        {
            if (string.IsNullOrEmpty(text) || string.IsNullOrEmpty(language)) return text;
            if (string.Equals(language, "uk", StringComparison.OrdinalIgnoreCase)) language = "UA";
            if (!Terms.TryGetValue(language, out var terms)) return text;
            Regex matcher;
            lock (PatternLock)
            {
                if (!Patterns.TryGetValue(language, out matcher))
                {
                    var phrases = terms.Keys.OrderByDescending(x => x.Length).Select(x => {
                        string escaped = Regex.Escape(x);
                        return x.Length <= 2 && Regex.IsMatch(x, @"^[A-Za-zА-Яа-яІіЇїЄє]+$") ? @"(?<![\p{L}\p{N}])" + escaped + @"(?![\p{L}\p{N}])" : escaped;
                    });
                    matcher = new Regex(string.Join("|", phrases), RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
                    Patterns[language] = matcher;
                }
            }
            var highlighted = matcher.Replace(text, match => "<color=" + terms[match.Value] + ">" + match.Value + "</color>");
            var lines = highlighted.Split('\n');
            if (token == "KINGMOD_TUTORIAL_FORM_MASTERY" && lines.Length > 1) lines[lines.Length - 1] = "<color=#aaaaaa>" + lines[lines.Length - 1] + "</color>";
            if (token == "KINGMOD_TUTORIAL_KAIOKEN" && lines.Length >= 8) for (int i = lines.Length - 3; i < lines.Length; i++) lines[i] = "<color=#aaaaaa>" + lines[i] + "</color>";
            return string.Join("\n", lines);
        }
    }
